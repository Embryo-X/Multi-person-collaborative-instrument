/**
 * ==============================================================
 * 按键组件 — GPIO 按键扫描 + 软件消抖
 * ==============================================================
 * 功能：
 *   - 检测按键短按事件（带 20ms 消抖）
 *   - 检测按键按下/释放状态
 *   - 支持内部上拉，按键只需对地连接
 *
 * 引脚配置在此文件顶部，可以直接修改
 * ==============================================================
 */

#ifndef BUTTON_H
#define BUTTON_H

#include "driver/gpio.h"
#include "esp_err.h"

/* ========== 引脚 & 参数配置（可按需修改）========== */

#define BTN_GPIO          GPIO_NUM_39   /* 按键引脚号               */
#define BTN_DEBOUNCE_MS   20           /* 消抖时间（毫秒）          */

/* ========== API 函数声明 ========== */

/**
 * @brief 初始化按键 GPIO
 *        配置为输入模式 + 内部上拉
 *        （按下按键时引脚接地 → 读低电平；松开时上拉 → 读高电平）
 * @return ESP_OK 成功
 */
esp_err_t button_init(void);

/**
 * @brief 检测按键是否被按下（单次检测，无消抖）
 *        用于需要连续检测的场景
 * @return 1 = 按下（低电平），0 = 未按下（高电平）
 */
uint8_t button_is_pressed(void);

/**
 * @brief 检测一次完整的"按下→松开"事件（带消抖）
 *        调用此函数不会阻塞，它会记住上次的状态
 *        在 loop 中反复调用，每检测到一次完整的按击返回 1
 *
 *        工作流程：
 *        空闲(高) → 检测到低电平 → 等20ms再读 → 确认低 → 标记为"按下"
 *       → 等待释放(高电平) → 等20ms再读 → 确认高 → 返回 1
 *
 * @return 1 = 检测到一次完整点击，0 = 没有
 */
uint8_t button_read_click(void);

#endif /* BUTTON_H */

/**
 * ==============================================================
 * 按键组件 — GPIO 按键扫描 + 软件消抖
 * ==============================================================
 * 功能：
 *   - 检测按键短按事件（带 20ms 消抖）
 *   - 检测按键按下/释放状态
 *   - 支持内部上拉，按键只需对地连接
 *
 * 引脚配置在此文件顶部，可以直接修改
 * ==============================================================
 */

#ifndef BUTTON_H
#define BUTTON_H

#include "driver/gpio.h"
#include "esp_err.h"

/* ========== 引脚 & 参数配置（可按需修改）========== */

#define BTN_GPIO          GPIO_NUM_39   /* 按键引脚号               */
#define BTN_DEBOUNCE_MS   20           /* 消抖时间（毫秒）          */
#define BTN_DOUBLE_MS     300          /* 双击判定窗口（毫秒）      */

/* ========== API 函数声明 ========== */

/**
 * @brief 初始化按键 GPIO
 *        配置为输入模式 + 内部上拉
 *        （按下按键时引脚接地 → 读低电平；松开时上拉 → 读高电平）
 * @return ESP_OK 成功
 */
esp_err_t button_init(void);

/**
 * @brief 检测按键是否被按下（单次检测，无消抖）
 *        用于需要连续检测的场景
 * @return 1 = 按下（低电平），0 = 未按下（高电平）
 */
uint8_t button_is_pressed(void);

/**
 * @brief 检测"按下→松开"事件，并区分单击/双击（带消抖）
 *        非阻塞，反复调用。返回：
 *          0 = 无事件
 *          1 = 单击（双击窗口内无第二击）
 *          2 = 双击（窗口内两次点击）
 *        注意：单击判定会在 BTN_DOUBLE_MS 窗口结束后才返回，略有延迟。
 */
uint8_t button_read_event(void);

/**
 * @brief 兼容旧接口：任何一次完整点击（单击或双击）都返回 1
 */
uint8_t button_read_click(void);

#endif /* BUTTON_H */

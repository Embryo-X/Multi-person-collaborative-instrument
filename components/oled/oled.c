/* ==============================================================
 * 帧缓冲像素操作
 * ============================================================== */
static inline void fb_set(int x, int y, uint16_t c) {
    if (x < OLED_WIDTH && y < OLED_HEIGHT)
        g_fb[y * OLED_WIDTH + x] = c;
}

static void fb_fill(uint16_t c) {
    for (int i = 0; i < OLED_WIDTH * OLED_HEIGHT; i++)
        g_fb[i] = c;
}

/* 清一个矩形区域为黑 */
static void fb_clear_region(int x0, int y0, int x1, int y1)
{
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 >= OLED_WIDTH) x1 = OLED_WIDTH - 1;
    if (y1 >= OLED_HEIGHT) y1 = OLED_HEIGHT - 1;
    for (int y = y0; y <= y1; y++)
        for (int x = x0; x <= x1; x++)
            g_fb[y * OLED_WIDTH + x] = BLACK;
}

/* ---- 画 ASCII 字符到帧缓冲 ---- */
static void draw_asc(int x0, int y0, char ch)
{
    if (ch < 0x20 || ch > 0x7E) return;
    uint8_t idx = ch - 0x20;
    for (int col = 0; col < FONT_ASC_WIDTH; col++) {
        uint8_t b = font_6x8[idx][col];
        for (int row = 0; row < 8; row++) {
            if (b & (1 << row))
                fb_set(x0 + col, y0 + row, WHITE);
        }
    }
}

/* ---- 画中文字符到帧缓冲 ---- */
static void draw_cn(int x0, int y0, const uint8_t *bm)
{
    if (!bm) return;
    for (int col = 0; col < FONT_CN_WIDTH; col++) {
        uint8_t upper = bm[col];       /* 上半 (rows 0-7) */
        uint8_t lower = bm[16 + col];  /* 下半 (rows 8-15) */
        for (int row = 0; row < 8; row++) {
            if (upper & (1 << (7 - row)))
                fb_set(x0 + col, y0 + row, WHITE);
            if (lower & (1 << (7 - row)))
                fb_set(x0 + col, y0 + 8 + row, WHITE);
        }
    }
}

/* ---- UTF-8 ---- */
static uint8_t utf8_len(uint8_t b) {
    if (b < 0x80) return 1;
    if ((b & 0xF0) == 0xE0) return 3;
    return 0;
}

/* 竖排辅助函数前向声明（供 oled_draw_two_lines 等先调用） */
static int text_vertical_height(const char *text);
static void draw_vertical_text(int x, int y, const char *text);

/* ==============================================================
 * 公开 API
 * ============================================================== */

esp_err_t oled_init(void)
{
    ESP_RETURN_ON_ERROR(nv3007_init(), TAG, "nv3007_init");

    fb_fill(BLACK);
    nv3007_draw_region(0, 0, OLED_WIDTH - 1, OLED_HEIGHT - 1, g_fb);

    ESP_LOGI(TAG, "OLED 绘制层初始化完成");
    return ESP_OK;
}

void oled_clear(void)
{
    fb_fill(BLACK);
    nv3007_draw_region(0, 0, OLED_WIDTH - 1, OLED_HEIGHT - 1, g_fb);
}

void oled_draw_two_lines(const char *l1, const char *l2)
{
    /* 两段文字竖排在同一列，中间留 20px 间隔 */
    int h1 = text_vertical_height(l1);
    int h2 = text_vertical_height(l2);
    int gap = 20;
    int total = h1 + gap + h2;
    uint8_t sx = (OLED_WIDTH - FONT_CN_WIDTH) / 2;
    uint8_t sy = (total < OLED_HEIGHT) ? (OLED_HEIGHT - total) / 2 : 0;

    fb_clear_region(VERT_X0, 0, VERT_X1, OLED_HEIGHT - 1);
    draw_vertical_text(sx, sy, l1);
    draw_vertical_text(sx, sy + h1 + gap, l2);
    nv3007_draw_region(0, 0, OLED_WIDTH - 1, OLED_HEIGHT - 1, g_fb);
}

void oled_draw_vol(uint8_t pct)
{
    char buf[8];
    snprintf(buf, sizeof(buf), "%d%%", (int)pct);
    int w = strlen(buf) * FONT_ASC_WIDTH;
    int sx = OLED_WIDTH - w - 2;
    int sy = 4;
    for (int y = sy; y < sy + 8; y++)
        for (int x = sx; x < OLED_WIDTH; x++)
            fb_set(x, y, BLACK);
    for (int i = 0; buf[i]; i++)
        draw_asc(sx + i * FONT_ASC_WIDTH, sy, buf[i]);
    nv3007_draw_region(sx, sy, OLED_WIDTH - 1, sy + 7, &g_fb[sy * OLED_WIDTH + sx]);
}

void oled_refresh(void)
{
    nv3007_draw_region(0, 0, OLED_WIDTH - 1, OLED_HEIGHT - 1, g_fb);
}

void oled_draw_text(uint8_t x, uint8_t y, const char *text)
{
    uint8_t cx = x;
    while (*text && cx < OLED_WIDTH) {
        uint8_t l = utf8_len(*text);
        if (l == 1) {
            draw_asc(cx, y, *text);
            cx += FONT_ASC_WIDTH;
            text++;
        } else if (l == 3) {
            const uint8_t *bm = cn_font_lookup((uint8_t)text[0], (uint8_t)text[1], (uint8_t)text[2]);
            draw_cn(cx, y, bm);
            cx += FONT_CN_WIDTH;
            text += 3;
        } else text++;
    }
}

/* 竖排文字总高度：中文16px/字，ASCII 8px/字符 */
static int text_vertical_height(const char *text)
{
    int h = 0;
    while (*text) {
        uint8_t l = utf8_len(*text);
        if (l == 3) { h += FONT_CN_WIDTH; text += 3; }
        else if (l == 1) { h += 8; text++; }
        else text++;
    }
    return h;
}

/* 竖排绘制到帧缓冲（x 固定，y 从上到下递增） */
static void draw_vertical_text(int x, int y, const char *text)
{
    uint8_t cy = y;
    while (*text && cy + 8 <= OLED_HEIGHT) {
        uint8_t l = utf8_len(*text);
        if (l == 1) {
            draw_asc(x, cy, *text);
            cy += 8;
            text++;
        } else if (l == 3) {
            const uint8_t *bm = cn_font_lookup((uint8_t)text[0], (uint8_t)text[1], (uint8_t)text[2]);
            draw_cn(x, cy, bm);
            cy += FONT_CN_WIDTH;
            text += 3;
        } else text++;
    }
}

void oled_draw_center_text(const char *text)
{
    int total_h = text_vertical_height(text);
    uint8_t sx = (OLED_WIDTH - FONT_CN_WIDTH) / 2;   /* 中文字居中 */
    uint8_t sy = (total_h < OLED_HEIGHT) ? (OLED_HEIGHT - total_h) / 2 : 0;

    /* 清中央文字列（保留右上角音量），竖排绘制后整屏刷新防残留 */
    fb_clear_region(VERT_X0, 0, VERT_X1, OLED_HEIGHT - 1);
    draw_vertical_text(sx, sy, text);
    nv3007_draw_region(0, 0, OLED_WIDTH - 1, OLED_HEIGHT - 1, g_fb);
}
